"""Write paper/numbers_lme.tex: macros for the LongMemEval-S offline arm (20 Oct 2026 runs). Read-only over
paper2/out; a missing run yields "--" so the paper always compiles.
  .venv/bin/python paper2/paper/make_numbers_lme.py
"""
from __future__ import annotations
import json, math, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
OUT = ROOT / "paper2" / "out"
TEX = ROOT / "paper2" / "paper" / "numbers_lme.tex"
from paper2 import stats as S  # noqa: E402

RUNS = {"AdmitAll": "lme_s_admit_all_full_500", "Fit": "lme_s_graph_gate_struct_m0.5_500", "Prior": "lme_s_graph_gate_m0.5_500",
        "Random": "lme_s_random_m0.5_500", "Heat": "lme_s_heat_m0.5_500"}
CATS = {"SsUser": "single-session-user", "SsAssistant": "single-session-assistant", "SsPreference": "single-session-preference",
        "MultiSession": "multi-session", "TemporalReasoning": "temporal-reasoning", "KnowledgeUpdate": "knowledge-update"}
M: dict[str, str] = {}


def put(k, v, fmt="{:.3f}"):
    M[k] = "--" if v is None or (isinstance(v, float) and math.isnan(v)) else (fmt.format(v) if not isinstance(v, str) else v)


def summ(run):
    p = OUT / run / "summary.json"
    return json.loads(p.read_text()) if p.exists() else None


for code, run in RUNS.items():
    d = summ(run)
    for k in ("hit", "frac", "mrr"):
        put(f"lme{k.capitalize()}{code}", d["overall"][k]["mean"] if d else None)
    put(f"lmeLive{code}", int(d["totals"]["live_facts"]) if d else None, "{:,}")
    for cc, cat in CATS.items():
        put(f"lmeHit{code}{cc}", d["by_category"].get(cat, {}).get("hit", {}).get("mean") if d else None)
    if d and code == "AdmitAll":
        put("lmeNq", d["n"], "{:d}")
pairs = [("Fit", "Random"), ("Fit", "Prior"), ("Fit", "Heat"), ("Prior", "Random"), ("Random", "Heat")]
for metric in ("hit", "mrr"):
    tag = metric.capitalize()
    for a, b in pairs:
        try:
            r = S.compare(S.load_qa(str(OUT / RUNS[a]), metric), S.load_qa(str(OUT / RUNS[b]), metric))
            put(f"lmeD{tag}{a}{b}", r["mean_conv"], "{:+.3f}")
            put(f"lmeP{tag}{a}{b}", r["perm"]["p"], "{:.3f}")
            put(f"lmeCiLo{tag}{a}{b}", r["t"]["lo"], "{:+.3f}"); put(f"lmeCiHi{tag}{a}{b}", r["t"]["hi"], "{:+.3f}")
            put(f"lmeK{tag}{a}{b}", r["k"], "{:d}"); put(f"lmeWins{tag}{a}{b}", r["wins"], "{:d}"); put(f"lmeLosses{tag}{a}{b}", r["losses"], "{:d}")
        except Exception as e:  # noqa: BLE001
            for k in ("D", "P", "CiLo", "CiHi", "K", "Wins", "Losses"):
                M.setdefault(f"lme{k}{tag}{a}{b}", "--")
            print("stats failed for", a, b, metric, e, file=sys.stderr)
# Holm over the three fitted-gate comparisons on evidence-hit
ps = [float(M.get(f"lmePHit{'Fit'}{b}", "nan")) for b in ("Random", "Prior", "Heat")]
if all(p == p for p in ps):
    for b, h in zip(("Random", "Prior", "Heat"), S.holm(ps)):
        put(f"lmeHolmHitFit{b}", h, "{:.3f}")
aucs, imp, nov = [], [], []
for f in sorted((OUT / "w_lme").glob("structural_fold*.json")):
    w = json.loads(f.read_text()); aucs.append(w["cv_auc_mean"])
    d = dict(zip(w["names"], w["w"])); imp.append(d.get("impact", 0)); nov.append(d.get("novelty", 0))
put("lmeCvAucMin", min(aucs) if aucs else None); put("lmeCvAucMax", max(aucs) if aucs else None)
put("lmeWImpactMin", min(imp) if imp else None, "{:+.2f}"); put("lmeWImpactMax", max(imp) if imp else None, "{:+.2f}")
put("lmeWNoveltyMin", min(nov) if nov else None, "{:+.2f}"); put("lmeWNoveltyMax", max(nov) if nov else None, "{:+.2f}")
TEX.write_text("% generated by paper2/paper/make_numbers_lme.py; do not edit\n" + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in sorted(M.items())))
print(f"wrote {TEX} with {len(M)} macros; '--' entries: {sum(1 for v in M.values() if v == '--')}")
