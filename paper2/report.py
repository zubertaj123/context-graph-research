"""Generate docs/03-results-loo.md from paper2/out only, so every number in the note names the run
directory it came from (critique A10). Interpretation is written by hand below the marker line and is
preserved across regenerations.

  python -m paper2.report
"""
from __future__ import annotations

import glob
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "paper2" / "out"
DOC = ROOT / "paper2" / "docs" / "03-results-loo.md"
PY = str(ROOT / ".venv" / "bin" / "python")
MARK = "<!-- interpretation below this line is hand-written and preserved -->"
ORDER = ["graph_gate", "graph_gate_struct", "graph_gate_full", "amac_fit", "amac_lite", "heat", "impact_2010", "random", "siv_2010"]
LABELS = {"graph_gate": "structural gate, hand-set prior weights (not in the frozen pre-registration)",
          "graph_gate_struct": "structural-only gate, 7 graph features, fitted leave-one-out",
          "graph_gate_full": "structural + surface gate, 13 features, fitted leave-one-out",
          "amac_fit": "A-MAC feature definitions, weights fitted leave-one-out by the same learner",
          "amac_lite": "A-MAC feature definitions, hand-set weights, no utility call",
          "heat": "length + revisit heuristic (MemoryOS-inspired)", "impact_2010": "Impact alone (2010), ablation",
          "random": "uniform random score", "siv_2010": "Trust x Impact (al-Saffar & Heileman 2010) at turn granularity"}


def load(name):
    p = OUT / name / "summary.json"
    return json.loads(p.read_text()) if p.exists() else None


def run(cmd: list[str]) -> str:
    try:
        return subprocess.run([PY, "-m"] + cmd, cwd=ROOT, capture_output=True, text=True, timeout=600).stdout.strip()
    except Exception as e:  # noqa: BLE001
        return f"(failed: {e})"


def main():
    aa = load("locomo_admit_all")
    lines = ["# LoCoMo offline arm, leave-one-conversation-out (generated by `python -m paper2.report`)", ""]
    if aa:
        pv = aa.get("provenance", {})
        lines += [f"Code hash `{pv.get('code_hash')}`, data `{pv.get('data_file')}` sha256 `{str(pv.get('data_sha256'))[:16]}…`, written {pv.get('written_at')}.",
                  "Learned gates are fitted on the other nine conversations (`paper2/out/w_loo/`), memory is matched by bisection to a fraction of each",
                  "conversation's admit-all live facts (tolerance 5%), retrieval is BM25 top-20 + 1-hop, value is evidence recall (no model calls).", "",
                  "## 1. Ceiling and graph shape (admit everything, `locomo_admit_all`)", "",
                  "| conversation | candidates | live facts | invalidated | evidence-hit | non-hub vertices | share deg≥2 | share non-hub→non-hub edges | components |",
                  "|---|---|---|---|---|---|---|---|---|"]
        qa_by = {}
        for l in open(OUT / "locomo_admit_all" / "qa.jsonl"):
            r = json.loads(l)
            if r["hit"] == r["hit"]:
                qa_by.setdefault(r["conv"], []).append(r["hit"])
        for c in aa["conversations"]:
            h = qa_by.get(c["conv"], [])
            lines.append(f"| {c['conv']} | {c['candidates']} | {c['live_facts']} | {c['invalidated']} | {sum(h)/len(h) if h else float('nan'):.3f} | {c['shape_non_hub_vertices']} | "
                         f"{c['shape_share_non_hub_deg_ge2']:.2f} | {c['shape_share_edges_non_hub_to_non_hub']:.2f} | {c['shape_non_hub_components']} |")
        o = aa["overall"]["hit"]
        lines += ["", f"Overall evidence-hit {o['mean']:.3f} [{o['ci95'][0]:.3f}, {o['ci95'][1]:.3f}] over {aa['n']} questions; per category: " +
                  ", ".join(f"{k} {v['hit']['mean']:.3f} (n={v['hit']['n']})" for k, v in sorted(aa["by_category"].items()) if "hit" in v) + ".", ""]
    # matched-size table
    lines += ["## 2. Matched memory size, all 10 conversations as test units", ""]
    for size in ("0.25", "0.5", "0.75"):
        rows = []
        for pol in ORDER:
            d = load(f"merged_loo_{pol}_m{size}")
            if d:
                o = d["overall"]["hit"]
                rows.append((pol, LABELS.get(pol, d.get("policy_label", pol)), d["mean_admit_rate"], int(d["totals"]["live_facts"]), d.get("mean_size_gap", float("nan")), o["mean"], o["ci95"],
                             d["overall"].get("frac", {}).get("mean", float("nan")), d["overall"].get("mrr", {}).get("mean", float("nan")), d["name"]))
        if not rows:
            continue
        lines += [f"### memory = {float(size):.0%} of admit-all", "", "| policy | label | admit rate | live facts | size gap | evidence-hit [95% q-CI] | frac | MRR | run |", "|---|---|---|---|---|---|---|---|---|"]
        for r in sorted(rows, key=lambda r: -r[5]):
            lines.append(f"| {r[0]} | {r[1]} | {r[2]:.2f} | {r[3]} | {r[4]:.3f} | **{r[5]:.3f}** [{r[6][0]:.3f}, {r[6][1]:.3f}] | {r[7]:.3f} | {r[8]:.3f} | `{r[9]}` |")
        lines.append("")
    # statistics
    ref = "merged_loo_graph_gate_struct_m0.5"
    others = [f"merged_loo_{p}_m0.5" for p in ("random", "siv_2010", "impact_2010", "heat", "amac_lite", "amac_fit", "graph_gate", "graph_gate_full")]
    if (OUT / ref).exists():
        lines += ["## 3. Primary test: sign-flip permutation on per-conversation paired differences (10 clusters)", "",
                  "Reference: structural-only gate (fitted leave-one-out), memory = 50%. Output of `python -m paper2.stats`:", "", "```",
                  run(["paper2.stats", str(OUT / ref)] + [str(OUT / o) for o in others if (OUT / o).exists()]), "```", "",
                  "Reference: prior-weight structural gate:", "", "```",
                  run(["paper2.stats", str(OUT / "merged_loo_graph_gate_m0.5")] + [str(OUT / f"merged_loo_{p}_m0.5") for p in ("random", "heat", "amac_lite", "amac_fit", "graph_gate_struct") if (OUT / f"merged_loo_{p}_m0.5").exists()]),
                  "```", ""]
    # poisoning
    prow = []
    for cond in ("sourceless", "sourceless_tier", "lower", "lower_tier"):
        for pol in ("random", "graph_gate", "graph_gate_struct"):
            d = load(f"merged_poison_{cond}_{pol}_m0.5")
            if d and d["totals"]["poison_candidates"]:
                prow.append((cond, pol, d["totals"]["poison_admitted"], d["totals"]["poison_candidates"], d.get("poison_retrieved_share", float("nan")), d["overall"]["hit"]["mean"], d["name"]))
    if prow:
        lines += ["## 4. Poisoning arm (H4), 10% fabricated candidates, memory = 50%", "",
                  "`sourceless`: poison carries the same tier confidence as real candidates (no policy can see it). `lower`: poison tier 0.4 vs 0.6. `_tier`: the",
                  "policy score is multiplied by mean tier confidence. The injected set is identical across policies.", "",
                  "| condition | policy | poison admitted | share | questions retrieving ≥1 poison fact | evidence-hit | run |", "|---|---|---|---|---|---|---|"]
        for r in prow:
            lines.append(f"| {r[0]} | {r[1]} | {int(r[2])} / {int(r[3])} | {r[2]/r[3]:.2f} | {r[4]:.3f} | {r[5]:.3f} | `{r[6]}` |")
        lines.append("")
    # diagnostics
    if (OUT / "locomo_admit_all" / "turns.jsonl").exists():
        lines += ["## 5. Diagnostics (admit-all candidate stream, all 10 conversations)", "", "```",
                  run(["paper2.analysis", "features", str(OUT / "locomo_admit_all" / "turns.jsonl")]), "```", "", "```",
                  run(["paper2.analysis", "shape", str(OUT / "locomo_admit_all" / "turns.jsonl")]), "```", ""]
    figs = sorted(p.name for p in (OUT / "fig").glob("*.png")) if (OUT / "fig").exists() else []
    if figs:
        lines += ["Figures: " + ", ".join(f"`paper2/out/fig/{f}`" for f in figs), ""]
    auto = "\n".join(lines)
    hand = ""
    if DOC.exists() and MARK in DOC.read_text():
        hand = DOC.read_text().split(MARK, 1)[1]
    DOC.write_text(auto + "\n" + MARK + (hand if hand.strip() else "\n\n## 6. Interpretation\n\n(to be written after reading sections 1–5)\n"))
    print(f"written {DOC}")


if __name__ == "__main__":
    main()
